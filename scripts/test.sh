#!/usr/bin/env bash
# test.sh — full verification suite: pytest + ruff + the 7 per-use-case scripts.
# Regenerates docs/test-results.md (committed) and exits non-zero when any
# step fails. No -e on purpose: every step runs so the results table is
# complete even with failures.
set -uo pipefail
cd "$(dirname "$0")/.."

RESULTS_FILE="docs/test-results.md"
TS="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
overall=0
rows=()

run_step() {
  local name="$1"
  shift
  echo
  echo "=== $name ==="
  if "$@"; then
    echo "--- PASS: $name"
    rows+=("| $name | PASS | $TS |")
  else
    echo "--- FAIL: $name" >&2
    overall=1
    rows+=("| $name | FAIL | $TS |")
  fi
}

run_step "pytest (full suite)" uv run pytest -q
run_step "ruff check" uv run ruff check

for n in 1 2 3 4 5 6 7; do
  run_step "test-uc-0$n.sh" bash "scripts/test-uc-0$n.sh"
done

{
  echo "# Test Results"
  echo
  echo "Generated by scripts/test.sh on $TS (UTC). Do not edit by hand —"
  echo "re-run ./scripts/test.sh to regenerate."
  echo
  echo "| Script | Result | Timestamp |"
  echo "|---|---|---|"
  printf '%s\n' "${rows[@]}"
  echo
  echo "Notes:"
  echo
  echo "- test-uc-06.sh is a green-skip: polyglot (npm) conversion is v1.1 scope (F-036)."
  echo '- Each test-uc-*.sh uses a throwaway $PROTOX_DATA_DIR / $PROTOX_WORKSPACE under /tmp'
  echo '  and forces $PROTOX_TF_API_KEY empty, so results are hermetic and offline.'
} > "$RESULTS_FILE"

echo
echo "results written to $RESULTS_FILE"
if [[ $overall -eq 0 ]]; then
  echo "ALL GREEN"
else
  echo "FAILURES PRESENT (see table above)" >&2
fi
exit $overall
